package dev.vlformat.cli

import dev.vlformat.config.FormatConfig
import java.io.BufferedReader
import java.io.PrintStream
import java.nio.file.Files
import java.nio.file.Path

/**
 * `vl-format init` — interactive `.vlformat` creator. Walks through the
 * options that matter most, validates every answer, and writes a commented
 * properties file. Every prompt has a sensible default (just press Enter);
 * when stdin runs dry (piped/non-interactive use) defaults are taken.
 */
class InitWizard(private val input: BufferedReader, private val out: PrintStream) {

    fun run(dir: Path): Int {
        val target = dir.resolve(FormatConfig.FILE_NAME)
        out.println("vl-format config creator")
        out.println("Writing: ${target.toAbsolutePath().normalize()}")
        out.println("Press Enter to accept the [default].")
        out.println()

        if (Files.exists(target) && !askBool("A .vlformat already exists here. Overwrite?", false)) {
            out.println("Aborted; existing config untouched.")
            return 1
        }

        val indentSize = askInt("Indent size (spaces per level)", 4, 1..16)
        val continuationIndent = askInt("Continuation indent (wrapped expressions, open parens)", indentSize * 2, 0..64)
        val maxLineLength = askInt("Max line length — long lines are reported, never re-wrapped (0 = off)", 120, 0..1000)
        val maxBlankLines = askInt("Max consecutive blank lines", 1, 0..10)
        val attachBraces = askBool("Attach '{' to the previous line (K&R / Kotlin style)?", true)
        val attachClauses = askBool("Attach else/catch/finally/do-while onto the '}' line?", true)
        val alignCommentStars = askBool("Realign '*' gutters in Javadoc/KDoc block comments?", true)
        val insertFinalNewline = askBool("Guarantee exactly one newline at end of file?", true)

        val content = buildString {
            appendLine("# vl-format configuration (Java properties syntax).")
            appendLine("# Generated by `vl-format init`. Discovery: nearest .vlformat walking up")
            appendLine("# from each formatted file wins; delete a line to fall back to defaults.")
            appendLine()
            appendLine("indentSize=$indentSize")
            appendLine("continuationIndent=$continuationIndent")
            appendLine("# 0 disables the long-line report")
            appendLine("maxLineLength=$maxLineLength")
            appendLine("maxBlankLines=$maxBlankLines")
            appendLine("attachBraces=$attachBraces")
            appendLine("attachClauses=$attachClauses")
            appendLine("alignCommentStars=$alignCommentStars")
            appendLine("insertFinalNewline=$insertFinalNewline")
            appendLine()
            appendLine("# Disable built-in or plugin rules by name (comma-separated), e.g.:")
            appendLine("# disabledRules=blank-lines,attach-clauses")
        }
        Files.createDirectories(target.toAbsolutePath().normalize().parent)
        Files.writeString(target, content)
        out.println()
        out.println("Wrote ${target.toAbsolutePath().normalize()}")
        out.println("Try it: vl-format --dry-run .")
        return 0
    }

    private fun prompt(question: String, default: String): String {
        out.print("$question [$default]: ")
        out.flush()
        val line = input.readLine()?.trim()
        return if (line.isNullOrEmpty()) default else line
    }

    private fun askInt(question: String, default: Int, range: IntRange): Int {
        while (true) {
            val raw = prompt(question, default.toString())
            val value = raw.toIntOrNull()
            if (value != null && value in range) return value
            out.println("  Please enter a number in $range.")
            if (raw == default.toString()) return default // stdin exhausted; don't loop forever
        }
    }

    private fun askBool(question: String, default: Boolean): Boolean {
        while (true) {
            when (prompt(question, if (default) "Y/n" else "y/N").lowercase()) {
                "y", "yes", "true" -> return true
                "n", "no", "false" -> return false
                "y/n", "n/y" -> return default // Enter on default hint
                else -> out.println("  Please answer y or n.")
            }
        }
    }
}
